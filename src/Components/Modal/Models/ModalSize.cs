namespace Htmx.Components.Modal.Models;

/// <summary>
/// Defines the supported DaisyUI modal box sizes.
/// </summary>
public enum ModalSize
{
    /// <summary>
    /// Uses the default modal width.
    /// </summary>
    Default,

    /// <summary>
    /// Uses a small modal width.
    /// </summary>
    Small,

    /// <summary>
    /// Uses a large modal width.
    /// </summary>
    Large,

    /// <summary>
    /// Uses an extra-large modal width.
    /// </summary>
    ExtraLarge,

    /// <summary>
    /// Uses the full available modal width.
    /// </summary>
    Full
}
